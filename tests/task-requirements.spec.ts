  await page.getByRole('tab', { name: 'Hierarchy', exact: true }).click();
  await page.getByRole('button', { name: 'Deliver verified report', exact: true }).click();
  drawer = page.getByRole('dialog', { name: 'Task', exact: true });
  await choose(page, drawer.getByRole('combobox', { name: 'Status', exact: true }), 'Backlog');
  await drawer.getByRole('checkbox', { name: 'Verify Results reviewed' }).press('Space');
  await drawer.getByRole('button', { name: 'Save', exact: true }).click();
  const reopened = (await state(page)).tasks.find((item: { title: string }) => item.title === 'Deliver verified report');
  expect(reopened.status).toBe('todo'); expect(reopened.completion[0].done).toBe(false);

  await page.evaluate(() => { localStorage.setItem('anumat-locale', 'km'); localStorage.setItem('anumat-theme', 'dark'); });
  await page.reload();
