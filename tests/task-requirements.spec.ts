  await settings.getByRole('textbox', { name: 'Default readiness requirements' }).fill('Scope is agreed');
  await settings.getByRole('textbox', { name: 'Default completion requirements' }).fill('Results reviewed');
  await page.screenshot({ path: `test-results/task-settings-${info.project.name}.png`, animations: 'disabled' });
  await settings.getByRole('button', { name: 'Save statuses' }).click();
  let drawer = await create(page, 'Deliver verified report');
