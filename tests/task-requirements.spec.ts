  await page.getByRole('button', { name: 'Approve verified delivery', exact: true }).click();
  drawer = page.getByRole('dialog', { name: 'Task', exact: true });
  await choose(page, drawer.getByRole('combobox', { name: 'Status', exact: true }), 'Done');
  await drawer.getByRole('button', { name: 'Save', exact: true }).click();
