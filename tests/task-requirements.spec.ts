  const criteria = drawer.getByRole('region', { name: 'Acceptance criteria', exact: true });
  await criteria.getByRole('button', { name: 'Add requirement' }).click();
  await criteria.getByRole('textbox').fill('All totals match source records');
  await drawer.getByRole('checkbox', { name: 'Verify Scope is agreed' }).press('Space');
  await drawer.getByRole('button', { name: 'Save', exact: true }).click();
  await expect.poll(async () => (await state(page)).tasks.find((item: { title: string }) => item.title === 'Deliver verified report').status).toBe('doing');
  await page.getByRole('checkbox', { name: 'Mark “Deliver verified report” done' }).press('Space');
  await expect(page.getByText('Verify every acceptance criterion first.')).toBeVisible();
  await page.getByRole('button', { name: 'Deliver verified report', exact: true }).click();
  drawer = page.getByRole('dialog', { name: 'Task', exact: true });
  await drawer.getByRole('checkbox', { name: 'Verify All totals match source records' }).press('Space');
  await drawer.getByRole('checkbox', { name: 'Verify Results reviewed' }).press('Space');
